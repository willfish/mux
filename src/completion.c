#include "completion.h"

#include <stdio.h>

void completion_bash(void) {
    printf("_mux() {\n"
           "    local cur prev commands projects flags backends\n"
           "    COMPREPLY=()\n"
           "    cur=\"${COMP_WORDS[COMP_CWORD]}\"\n"
           "    prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n"
           "    commands=\"start stop new edit open copy cp delete rm list ls debug local doctor "
           "implode i stop-all version help completions\"\n"
           "    flags=\"-a --append -b --backend -n --name -p --project-config -A --active "
           "--attach --no-attach --no-pre-window --local\"\n"
           "    backends=\"tmux herdr herdr-app\"\n"
           "\n"
           "    case \"$prev\" in\n"
           "        -b|--backend)\n"
           "            COMPREPLY=( $(compgen -W \"$backends\" -- \"$cur\") )\n"
           "            return 0\n"
           "            ;;\n"
           "        -p|--project-config)\n"
           "            COMPREPLY=( $(compgen -f -- \"$cur\") )\n"
           "            return 0\n"
           "            ;;\n"
           "        completions)\n"
           "            COMPREPLY=( $(compgen -W \"bash zsh fish\" -- \"$cur\") )\n"
           "            return 0\n"
           "            ;;\n"
           "    esac\n"
           "\n"
           "    if [[ \"$cur\" == -* ]]; then\n"
           "        COMPREPLY=( $(compgen -W \"$flags\" -- \"$cur\") )\n"
           "        return 0\n"
           "    fi\n"
           "\n"
           "    if [ \"$COMP_CWORD\" -eq 1 ]; then\n"
           "        projects=$(mux list 2>/dev/null)\n"
           "        COMPREPLY=( $(compgen -W \"$commands $projects\" -- \"$cur\") )\n"
           "        return 0\n"
           "    fi\n"
           "\n"
           "    case \"${COMP_WORDS[1]}\" in\n"
           "        start|s|stop|debug|delete|rm|d|copy|cp|c|edit|e|open|o)\n"
           "            projects=$(mux list 2>/dev/null)\n"
           "            COMPREPLY=( $(compgen -W \"$projects\" -- \"$cur\") )\n"
           "            return 0\n"
           "            ;;\n"
           "    esac\n"
           "}\n"
           "complete -F _mux mux\n");
}

void completion_zsh(void) {
    printf("#compdef mux\n"
           "\n"
           "_mux() {\n"
           "    local -a commands flags backends\n"
           "    commands=(\n"
           "        'start:Start a session or Herdr space'\n"
           "        'stop:Stop a session or Herdr space'\n"
           "        'new:Create a new project config'\n"
           "        'edit:Edit a project config'\n"
           "        'copy:Copy a project config'\n"
           "        'delete:Delete project configs'\n"
           "        'list:List available projects'\n"
           "        'debug:Print generated backend script'\n"
           "        'local:Start from local .tmuxinator.yml'\n"
           "        'doctor:Check dependencies'\n"
           "        'implode:Delete all configs'\n"
           "        'stop-all:Stop all active mux sessions'\n"
           "        'version:Print version'\n"
           "        'help:Show help'\n"
           "        'completions:Print shell completion script'\n"
           "    )\n"
           "    flags=(\n"
           "        '-a:Add windows to existing session'\n"
           "        '--append:Add windows to existing session'\n"
           "        '-b:Backend name'\n"
           "        '--backend:Backend name'\n"
           "        '-n:Override session name'\n"
           "        '--name:Override session name'\n"
           "        '-p:Specify config file path'\n"
           "        '--project-config:Specify config file path'\n"
           "        '-A:Only list active sessions'\n"
           "        '--active:Only list active sessions'\n"
           "        '--attach:Force attach on start'\n"
           "        '--no-attach:Do not attach on start'\n"
           "        '--no-pre-window:Skip project pre_window commands'\n"
           "        '--local:Create local .tmuxinator.yml'\n"
           "    )\n"
           "    backends=(tmux herdr herdr-app)\n"
           "\n"
           "    local prev=\"${words[CURRENT-1]}\"\n"
           "    case \"$prev\" in\n"
           "        -b|--backend)\n"
           "            _describe -t backends 'backends' backends\n"
           "            return\n"
           "            ;;\n"
           "        -p|--project-config)\n"
           "            _files\n"
           "            return\n"
           "            ;;\n"
           "    esac\n"
           "\n"
           "    if [[ \"${words[CURRENT]}\" == -* ]]; then\n"
           "        _describe -t flags 'options' flags\n"
           "        return\n"
           "    fi\n"
           "\n"
           "    if (( CURRENT == 2 )); then\n"
           "        local -a projects\n"
           "        projects=(${(f)\"$(mux list 2>/dev/null)\"})\n"
           "        _describe -t commands 'mux commands' commands\n"
           "        _describe -t projects 'projects' projects\n"
           "    else\n"
           "        case $words[2] in\n"
           "            start|s|stop|debug|delete|rm|d|copy|cp|c|edit|e|open|o)\n"
           "                local -a projects\n"
           "                projects=(${(f)\"$(mux list 2>/dev/null)\"})\n"
           "                _describe -t projects 'projects' projects\n"
           "                ;;\n"
           "            completions)\n"
           "                local -a shells\n"
           "                shells=(bash zsh fish)\n"
           "                _describe -t shells 'shells' shells\n"
           "                ;;\n"
           "        esac\n"
           "    fi\n"
           "}\n"
           "\n"
           "if [ \"$funcstack[1]\" = \"_mux\" ]; then\n"
           "    _mux \"$@\"\n"
           "else\n"
           "    compdef _mux mux\n"
           "fi\n");
}

